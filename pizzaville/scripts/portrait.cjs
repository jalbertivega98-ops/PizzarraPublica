const { chromium } = require('playwright')
;(async () => {
  const [out, q = ''] = process.argv.slice(2)
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
  const p = await b.newPage({ viewport: { width: 1080, height: 1080 } })
  p.on('pageerror', (e) => console.log('[pageerror]', e.message))
  await p.goto('http://localhost:5173/?portrait=1&' + q); await p.addStyleTag({ content: 'html,body,#root{background:transparent!important}' })
  await p.waitForSelector('canvas'); await p.waitForTimeout(6000)
  const data = await p.evaluate(() => document.querySelector('canvas').toDataURL('image/png'))
  require('fs').writeFileSync(out, Buffer.from(data.split(',')[1], 'base64'))
  await b.close()
})()
