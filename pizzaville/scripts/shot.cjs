// usage: node scripts/shot.cjs out.png "query" [w h t]
const { chromium } = require('playwright')
;(async () => {
  const [out, q = '', w = '1080', h = '1920', t = '0'] = process.argv.slice(2)
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
  const p = await b.newPage({ viewport: { width: +w, height: +h } })
  p.on('console', (m) => { if ((m.type() === 'error' || m.type() === 'warning') && !m.text().includes('GPU stall')) console.log('[' + m.type() + ']', m.text().slice(0, 300)) })
  p.on('pageerror', (e) => console.log('[pageerror]', e.message))
  const t0 = Date.now()
  await p.goto('http://localhost:5173/?record=1&' + q)
  await p.waitForFunction(() => window.__pv, null, { timeout: 120000, polling: 500 })
  console.log('pv', Date.now()-t0)
  await p.waitForTimeout(1500)
  await p.evaluate((t) => window.__pv.renderAt(t), +t)
  console.log('first frame', Date.now()-t0)
  await Promise.race([p.evaluate(() => window.__pv.ready()), new Promise(r=>setTimeout(()=>{console.log('ready TIMEOUT');r()},20000))])
  const t1 = Date.now()
  for (let i = 0; i < 3; i++) await p.evaluate((t) => window.__pv.renderAt(t), +t + i / 30)
  const t2 = Date.now()
  await p.screenshot({ path: out })
  console.log('ok load', t1 - t0, 'ms; frame', Math.round((t2 - t1) / 3), 'ms')
  await b.close()
})()
