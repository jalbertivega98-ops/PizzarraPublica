// usage: node scripts/shots.cjs outdir "query" w h  name=px,py,pz,lx,ly,lz,fov[@t] ...
const { chromium } = require('playwright')
;(async () => {
  const [dir, q = '', w = '540', h = '960', ...cams] = process.argv.slice(2)
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
  const p = await b.newPage({ viewport: { width: +w, height: +h } })
  p.on('console', (m) => { if ((m.type() === 'error' || m.type() === 'warning') && !/GPU stall|Clock/.test(m.text())) console.log('[' + m.type() + ']', m.text().slice(0, 300)) })
  p.on('pageerror', (e) => console.log('[pageerror]', e.message))
  const t0 = Date.now()
  await p.goto('http://localhost:5173/?record=1&orbit=0&' + q)
  await p.waitForFunction(() => window.__pv && window.__pv.setCam, null, { timeout: 120000, polling: 500 })
  await p.evaluate(() => window.__pv.renderAt(0))
  await p.evaluate(() => window.__pv.ready())
  console.log('loaded', Date.now() - t0)
  for (const c of cams) {
    const [name, spec] = c.split('=')
    const [cs, ts] = spec.split('@')
    if (cs !== '-') await p.evaluate((v) => window.__pv.setCam(v), cs.split(',').map(Number))
    const t1 = Date.now()
    await p.evaluate((t) => window.__pv.renderAt(t), +(ts ?? 2))
    const t2 = Date.now()
    await p.evaluate((t) => window.__pv.renderAt(t), +(ts ?? 2))
    const t3 = Date.now()
    const data = await p.evaluate(() => document.querySelector('canvas').toDataURL('image/png'))
    require('fs').writeFileSync(`${dir}/${name}.png`, Buffer.from(data.split(',')[1], 'base64'))
    console.log(name, 'first', t2 - t1, 'second', t3 - t2, 'grab', Date.now() - t3)
  }
  await b.close()
})()
